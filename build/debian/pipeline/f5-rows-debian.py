#!/usr/bin/env python3
"""f5-rows-debian.sh from userland-debs/f5-rows.sh: Debian base gates. Exact replacements, each must match once.
Usage: f5-rows-debian.py IN OUT"""
import sys
src, out = sys.argv[1:3]
t = open(src).read()
R = [
    # trixie base /etc/sysctl.conf (Armbian swappiness line), not v7.2 c9921db1
    ("= c9921db12138b2db ]", "= c909f751c8cb8694 ]"),
    # Debian /etc/environment carries no PATH line (Ubuntu does); gate keeps the mali and cairo checks
    (" && grep -q '\"'\"'^PATH='\"'\"' /etc/environment'", "'"),
]
for a, b in R:
    if t.count(a) != 1:
        sys.exit(f"f5-rows-debian: {a!r} matches {t.count(a)}")
    t = t.replace(a, b)
t = t.replace("# F5 rows of PARITY.md sections 5 and 8; generated by tools/parity.py",
              "# F5 rows of PARITY.md sections 5 and 8; generated by tools/parity.py\n"
              "# Debian edition: s5-sysctl hash of trixie base, s5-environment without PATH line (pipeline/f5-rows-debian.py)", 1)
open(out, "w").write(t)
